const dict: Record<Lang, Record<Key, string>> = { en, es };

export function translate(lang: Lang, k: Key, vars?: Record<string, string | number>) {
  let s = dict[lang][k];
  if (vars) for (const [a, b] of Object.entries(vars)) s = s.split(`{${a}}`).join(String(b));
  return s;
}
